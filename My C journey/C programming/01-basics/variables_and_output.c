#include <stdio.h>

int main() {
    // Declaring variables of different basic data types
    int age = 20;
    float temperature = 36.6f;
    char grade = 'A';

    // Printing variables using format specifiers
    printf("Age: %d\n", age);
    printf("Temperature: %.2f °C\n", temperature);
    printf("Grade: %c\n", grade);

    return 0;
}